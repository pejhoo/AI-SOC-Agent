def guardrail_check(response):

    lower = response.lower()

    for item in FORBIDDEN_ACTIONS:
        if item in lower:
            return {
                "allowed": False,
                "reason": f"Policy violation: {item}"
            }

    return {
        "allowed": True,
        "reason": "No violation detected"
    }



